function normalizeCoins(value) {
  const coins = Number(value);
  if (!Number.isFinite(coins) || coins < 0) return 0;
  return Math.floor(coins);
}

function normalizeUnlocked(unlocked = []) {
  return [...new Set(unlocked)].filter((id) => getMonster(id));
}

function normalizePlaced(placed = [], unlockedIds = []) {
  const unlocked = new Set(normalizeUnlocked(unlockedIds));
  return Array.from({ length: gridSize }, (_, index) => {
    const item = placed[index];
    const id = typeof item === "string" ? item : item?.id;
    if (!getMonster(id) || !unlocked.has(id)) return null;
    return { id };
  });
}

function normalizeMathProblem(problem) {
  if (!problem || !Number.isFinite(problem.a) || !Number.isFinite(problem.b)) return createMathProblem();
  return { a: problem.a, b: problem.b, answer: problem.a + problem.b };
}

function normalizeEvolutionSlots(slots = ["", ""]) {
  return [slots[0] || "", slots[1] || ""].map((id) => (getMonster(id) ? id : ""));
}

function normalizeEvolutionEgg(egg = [], unlockedIds = []) {
  const unlocked = new Set(normalizeUnlocked(unlockedIds));
  if (Array.isArray(egg)) {
    return {
      ...createEmptyEgg(),
      parents: egg.slice(0, 2).filter((id) => getMonster(id) && unlocked.has(id)),
    };
  }

  const cleanEgg = {
    ...createEmptyEgg(),
    ...egg,
    parents: Array.isArray(egg?.parents) ? egg.parents.slice(0, 2).filter((id) => getMonster(id)) : [],
    result: getMonster(egg?.result) ? egg.result : null,
    startedAt: Number.isFinite(egg?.startedAt) ? egg.startedAt : null,
    endsAt: Number.isFinite(egg?.endsAt) ? egg.endsAt : null,
  };

  if (!["empty", "ready", "incubating", "success", "failed"].includes(cleanEgg.status)) cleanEgg.status = "empty";
  return cleanEgg;
}

function createEmptyEgg() {
  return {
    status: "empty",
    parents: [],
    startedAt: null,
    endsAt: null,
    ruleTarget: null,
    chance: null,
    result: null,
  };
}

function createMathProblem() {
  const a = Math.floor(Math.random() * 5) + 1;
  const b = Math.floor(Math.random() * 5) + 1;
  return { a, b, answer: a + b };
}

