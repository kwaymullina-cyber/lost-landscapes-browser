function createMonsterEl(monster, placedIndex = null) {
  const body = document.createElement("span");
  body.className = "monster";
  body.style.setProperty("--monster-color", monster.color);
  body.style.animationDuration = `${0.9 + Math.random() * 0.4}s`;
  if (placedIndex !== null) {
    body.draggable = true;
    body.dataset.placedIndex = String(placedIndex);
    body.addEventListener("pointerdown", (event) => {
      beginDrag("board", placedIndex, null, event);
    });
    body.addEventListener("touchstart", (event) => {
      beginDrag("board", placedIndex, null, event);
    });
    body.addEventListener("dragstart", (event) => {
      event.stopPropagation();
      event.dataTransfer.setData("text/plain", String(placedIndex));
      event.dataTransfer.effectAllowed = "copy";
      setStatus(`Drag ${monster.name} into the evolution egg.`);
    });
  }
  body.innerHTML = monster.sprite
    ? `<img class="monster-sprite" src="${monster.sprite}" alt="">`
    : `<span class="mouth"></span><span class="feet"></span>`;
  return body;
}

function handleTileClick(index) {
  if (suppressNextTileClick) {
    suppressNextTileClick = false;
    return;
  }

  const current = state.placed[index];
  if (current) {
    const monster = getMonster(current.id);
    state.placed[index] = null;
    setStatus(`${monster.name} was removed from the island.`);
    render();
    return;
  }

  if (!state.selected) {
    state.targetTile = index;
    openModal("collection");
    setStatus("Choose one of your unlocked monsters to place here.");
    return;
  }

  const monster = getMonster(state.selected);
  if (!monster || !isUnlocked(monster.id)) {
    state.selected = null;
    setStatus("That monster is not unlocked yet.");
    render();
    return;
  }

  state.placed[index] = { id: monster.id };
  state.selected = null;
  setStatus(`${monster.name} joined the island. Tap it again if you want to remove it.`);
  ensureAudio();
  render();
}

