function buildEvolutionRules() {
  const chances = [80, 75, 70, 65, 60, 55, 50, 45, 40, 35];
  return monsters.slice(10).map((target, index) => {
    const pool = monsters.slice(0, 10 + index);
    const first = pool[index % pool.length].id;
    let second = pool[(index * 3 + 4) % pool.length].id;
    if (first === second) second = pool[(index + 1) % pool.length].id;
    return {
      target: target.id,
      parents: [first, second],
      chance: chances[index % chances.length],
    };
  });
}

function loadState() {
  try {
    const saved = JSON.parse(localStorage.getItem(storageKey));
    const unlocked = normalizeUnlocked(saved?.unlocked);
    return {
      ...defaultState,
      ...saved,
      coins: normalizeCoins(saved?.coins),
      selected: getMonster(saved?.selected) ? saved.selected : null,
      unlocked,
      placed: normalizePlaced(saved?.placed, unlocked),
      mathProblem: normalizeMathProblem(saved?.mathProblem),
      mathFeedback: null,
      mathCorrectCount: 0,
      evolutionSlots: normalizeEvolutionSlots(saved?.evolutionSlots),
      evolutionEgg: normalizeEvolutionEgg(saved?.evolutionEgg, unlocked),
      targetTile: null,
    };
  } catch {
    return createFreshState();
  }
}

