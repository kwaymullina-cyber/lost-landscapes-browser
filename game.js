function startEvolutionCountdownSound() {
  ensureAudio();
  stopAllLoops();
  stopEvolutionCountdownSound();
  if (!audioContext || state.muted) return;
  playCountdownTick();
  countdownSoundTimer = window.setInterval(playCountdownTick, 1000);
}

function stopEvolutionCountdownSound() {
  window.clearInterval(countdownSoundTimer);
  countdownSoundTimer = null;
}

function playCountdownTick() {
  if (!audioContext || state.muted || state.evolutionEgg.status !== "incubating") return;
  const remaining = Math.max(0, state.evolutionEgg.endsAt - Date.now());
  const progress = 1 - Math.min(1, remaining / evolutionDurationMs);
  const low = 110 + progress * 95;
  const high = 440 + progress * 260;
  playNote(low, "sawtooth", 0.035, 0.18);
  window.setTimeout(() => playNote(high, "square", 0.055, 0.08), 130);
  if (remaining <= 5000) {
    window.setTimeout(() => playNote(high * 1.25, "square", 0.045, 0.06), 330);
  }
}

