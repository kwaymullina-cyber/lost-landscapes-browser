function buyMonster(id) {
  const monster = getMonster(id);
  if (isUnlocked(id)) {
    setStatus(`${monster.name} is already unlocked.`);
    return;
  }
  if (state.coins < shopPrice) {
    setStatus(`Earn ${shopPrice - state.coins} more coin${shopPrice - state.coins === 1 ? "" : "s"} for ${monster.name}.`);
    return;
  }

  state.coins -= shopPrice;
  unlockMonster(id);
  setStatus(`${monster.name} is unlocked.`);
  render();
}

